"""Small, independent smoke/evaluation suite for the five supplied briefs.

The expectations below are written from the assignment, rather than generated by
the parser.  They intentionally check distinctions (mandatory/preferred and
hard/preferred location) that a happy-path schema-only test would miss.
"""
from __future__ import annotations

import json
import re
import sys
import time
from pathlib import Path

from parser import parse_brief

ROOT = Path(__file__).parent


def _walk(obj):
    yield obj
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield k
            yield from _walk(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _walk(v)


def _text(result) -> str:
    return json.dumps(result, ensure_ascii=False).lower()


def _key_values(result, names):
    names = {n.lower() for n in names}
    found = []
    def visit(x):
        if isinstance(x, dict):
            for k, v in x.items():
                if str(k).lower() in names:
                    found.append(v)
                visit(v)
        elif isinstance(x, list):
            for v in x:
                visit(v)
    visit(result)
    return found


def _contains(result, phrase):
    return phrase.lower() in _text(result)


def _assert(condition, message):
    if not condition:
        raise AssertionError(message)


def check(name, brief, assertions):
    result = parse_brief(brief)
    _assert(isinstance(result, dict), f"{name}: parser result is not an object")
    # Required structure: permit a top-level criteria wrapper, but require all
    # criteria concepts to be represented somewhere in the object.
    text = _text(result)
    required = ("role", "seniority", "experience", "skill", "location", "work", "domain", "compensation", "headcount", "exclusion")
    missing = [word for word in required if word not in text]
    _assert(not missing, f"{name}: missing required concepts {missing}")
    _assert("compensation" in text or "budget" in text, f"{name}: missing compensation/budget concept")
    for assertion in assertions:
        assertion(result)
    return result


def require(phrase, label):
    return lambda result: _assert(_contains(result, phrase), f"{label}: expected {phrase!r}")


def forbid(phrase, label):
    return lambda result: _assert(not _contains(result, phrase), f"{label}: unexpected {phrase!r}")


def f01(r):
    require("bengaluru", "F01")(r); require("6", "F01")(r); require("10", "F01")(r)
    require("java", "F01")(r); require("kafka", "F01")(r); require("postgresql", "F01")(r)
    require("kubernetes", "F01")(r); require("hybrid", "F01")(r); require("payments", "F01")(r)


def f02(r):
    require("3", "F02")(r); require("bangalore", "F02")(r); require("5", "F02")(r); require("8", "F02")(r)
    require("45", "F02")(r); require("55", "F02")(r); require("kafka", "F02")(r); require("java", "F02")(r)
    require("service company", "F02")(r)


def f03(r):
    # Deliberately vague brief: only role family can be extracted.
    for phrase in ("backend", "seniority", "experience", "location", "work_mode", "compensation", "headcount"):
        vals = _key_values(r, {phrase})
        if vals:
            _assert(all(v in (None, [], {}, "", "unknown") for v in vals), f"F03: hallucinated {phrase}: {vals}")
    for phrase in ("salary", "bengaluru", "bangalore", "pune", "java", "python", "kafka"):
        forbid(phrase, "F03")(r)


def f04(r):
    require("backend", "F04")(r); require("7", "F04")(r); require("go", "F04")(r)
    must = {str(v).lower() for v in (_key_values(r, {"must_have_skills"}) or [[]])[0]}
    preferred = {str(v).lower() for v in (_key_values(r, {"preferred_skills"}) or [[]])[0]}
    _assert("java" not in must and "java" not in preferred, "F04: Java fallback must not be promoted to a requirement")
    # five was explicitly superseded and Bangalore is a preference, not a hard location.
    require("preferred", "F04")(r)
    for phrase in ("5 years", "5-", '"min": 5', '"minimum": 5'):
        forbid(phrase, "F04")(r)


def f05(r):
    require("backend", "F05")(r); require("pune", "F05")(r); require("4", "F05")(r); require("6", "F05")(r)
    require("python", "F05")(r); require("django", "F05")(r); require("onsite", "F05")(r)
    require("30", "F05")(r); require("remote", "F05")(r)


def main():
    cases = [("F01", f01), ("F02", f02), ("F03", f03), ("F04", f04), ("F05", f05)]
    started = time.perf_counter(); passed = 0; totals = []
    for name, assertion in cases:
        brief = (ROOT / "briefs" / f"{name}.txt").read_text(encoding="utf-8")
        result = check(name, brief, [assertion])
        usage = result.get("usage") or result.get("token_usage") or {}
        if isinstance(usage, dict) and usage.get("total_tokens") is not None:
            totals.append(float(usage["total_tokens"]))
        (ROOT / "out").mkdir(exist_ok=True)
        (ROOT / "out" / f"{name}.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"PASS {name}")
        passed += 1
    elapsed = time.perf_counter() - started
    if totals:
        avg = sum(totals) / len(totals)
        print(f"Token usage: average total={avg:.1f} across {len(totals)} briefs (provider metadata/implementation estimate)")
        _assert(avg <= 500, f"token efficiency: average total {avg:.1f} exceeds 500")
    else:
        print("Token usage: unavailable in offline/local run; provider calls report usage when available.")
    print(f"Evaluation: {passed}/{len(cases)} briefs passed in {elapsed:.2f}s")


if __name__ == "__main__":
    try:
        main()
    except (AssertionError, OSError, ValueError) as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        raise SystemExit(1)
